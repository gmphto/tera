def test_the_library_read_bound_does_not_grow_with_the_shortlist(tmp_path, monkeypatch):
    """The reads one successful run executes are the same at 12 and at 100.

    The cache is stubbed to perform no SQL, so the trace holds only the landed
    library reads: the palette before the run and after ranking, the kick row,
    #25's own kick and population reads, one keyed shortlist read and the cache's
    model-version pin.
    """

    # #26's own reads are excluded from this bound, exactly as the criterion
    # states: the pin lookup and the pin write-back are the cache's bookkeeping.
    monkeypatch.setattr(decision_cache, "pinned_model_version", lambda *args, **kwargs: None)
    monkeypatch.setattr(decision_cache, "record_model_version", lambda *args, **kwargs: None)
    counts = {}
    case = _rule_case("a fully judged 12-candidate run")
    for size in (12, 100):
        directory = tmp_path / ("size-%d" % size)
        directory.mkdir()
        built = build_library(directory, {"kick": {"key": "known"},
                                          "basses": {"count": size,
                                                     "values": {"loudness": "index"}},
                                          "palette": {"kick": True, "bass": "bass-001"}})
        request = RecommendationRequest(palette_id=built.palette_id, revision=built.revision,
                                        limit=10)
        collaborators = RecommendationCollaborators(
            transport=ScriptedTransport(case["transport"]), environ={}, cache=_NoSqlCache())
        with closing(open_database(built.database)) as connection:
            trace = _Trace()
            connection.set_trace_callback(trace.record)
            try:
                result = run_recommendation(connection, request, collaborators=collaborators,
                                            cancelled=lambda: False)
            finally:
                connection.set_trace_callback(None)
            assert result.run.counts.scored == size
            assert result.run.evidence.double == 5 * size
            counts[size] = trace.reads()
    assert counts[12] == counts[100]
    # The whole run's constant read set: this route's palette read before the run
    # and after ranking (seven statements each, #24's record resolves every item),
    # its kick row (two), #25's own kick and population reads (eight) and the one
    # keyed shortlist read (two).
    assert counts[100] == 26


class _Trace:
    """Every read the connection executed during one request."""

    def __init__(self):
        self.statements = []

    def record(self, statement):
        self.statements.append(statement)

    def reads(self):
        return sum(1 for statement in self.statements
                   if statement.lstrip().upper().startswith("SELECT"))


class _NoSqlCache:
    """A #26 handle stubbed to perform no SQL: every lookup is a miss."""

    def lookup(self, connection, key, *, question):
        return decision_cache.CacheLookup(status="miss", reason="absent", judgment=None,
                                          decision=None, stale_found=False,
                                          entry_created_at=None)

    def store(self, connection, key, *, outcome):
        return decision_cache.StoreResult(stored=False, created_at=None, pruned=0)
