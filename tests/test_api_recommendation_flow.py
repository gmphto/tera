class FakeClock:
    """One thread-safe monotonic clock a test can advance."""

    def __init__(self, start=1000.0):
        self._value = start
        self._lock = threading.Lock()

    def __call__(self):
        with self._lock:
            return self._value

    def advance(self, seconds):
        with self._lock:
            self._value += seconds


def test_the_budget_returns_honest_partial_evidence_within_the_bound(tmp_path):
    case = _rule_case("a cache hit on the second request")
    clock = FakeClock()
    built_case = {"library": case["library"], "transport": case["transport"]}
    built = build_library(tmp_path, built_case["library"])
    collaborators, transport = collaborators_for(dict(built_case, monotonic=clock),
                                                 built=built, gate=lambda count: count == 1)
    collaborators = replace(collaborators, monotonic=clock)
    running = start_service(built.database, recommendations=collaborators)
    try:
        started = time.monotonic()
        outcome = {}

        def call():
            outcome["reply"] = running.client.post(
                "/recommendations", _request_body(built, case["requests"][0]))

        thread = threading.Thread(target=call, daemon=True)
        thread.start()
        assert transport is not None
        assert transport.blocked.wait(timeout=30), "the transport never blocked"
        health_started = time.monotonic()
        health = running.client.get("/health")
        assert health.status == 200
        assert time.monotonic() - health_started < 1
        clock.advance(30.0)
        transport.release.set()
        thread.join(30)
        assert not thread.is_alive()
        assert time.monotonic() - started < 27.0
        reply = outcome["reply"]
        assert reply.status == 200
        run = reply.body["run"]
        assert run["evidence"]["cache"] == 0
        assert run["evidence"]["interface"] == 0
        assert run["evidence"]["unavailable"] > 0
        assert run["evidence"]["unavailable"] + run["evidence"]["double"] == \
            5 * run["counts"]["scored"]
        assert running.client.get("/health").status == 200
        follow_up = running.client.post("/recommendations",
                                        _request_body(built, case["requests"][0]))
        assert follow_up.status == 200
    finally:
        running.stop()


def test_an_aborted_request_stops_at_the_stage_boundary_and_publishes_nothing(tmp_path):
    case = _rule_case("a cache hit on the second request")
    built_case = {"library": case["library"], "transport": case["transport"]}
    built = build_library(tmp_path, built_case["library"])
    collaborators, transport = collaborators_for(built_case, built=built,
                                                 gate=lambda count: count == 1)
    running = start_service(built.database, recommendations=collaborators)
    try:
        before = _palette_state(built.database, built.palette_id)
        opened = _send_raw(running.port, "/recommendations",
                           _request_body(built, case["requests"][0]))
        assert transport.blocked.wait(timeout=30), "the transport never blocked"
        first_batch = len(transport.calls)
        opened.close()
        # The requesting client is gone and the application publishes the
        # documented signal: #27's route context carries no connection, so this
        # is the one observable form of "the request socket has no client".
        running.app.__dict__[CLIENT_GONE_ATTRIBUTE] = True
        transport.release.set()
        deadline = time.monotonic() + 30
        while len(transport.calls) == first_batch and time.monotonic() < deadline:
            time.sleep(0.02)
        running.app.__dict__[CLIENT_GONE_ATTRIBUTE] = False
        assert len(transport.calls) == first_batch
        assert _palette_state(built.database, built.palette_id) == before
        assert running.client.get("/health").status == 200
        follow_up = running.client.post("/recommendations",
                                        _request_body(built, case["requests"][0]))
        assert follow_up.status == 200
    finally:
        running.stop()


def _send_raw(port, path, body):
    """One raw request whose socket the caller can close mid-flight."""

    opened = socket.create_connection(("127.0.0.1", port), timeout=30)
    payload = json.dumps(body).encode("utf-8")
    head = ("POST %s HTTP/1.1\r\nHost: 127.0.0.1:%d\r\nContent-Type: application/json\r\n"
            "Content-Length: %d\r\n\r\n" % (path, port, len(payload))).encode("ascii")
    opened.sendall(head + payload)
    return opened


