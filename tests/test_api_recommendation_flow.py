def test_an_unknown_band_takes_the_unavailable_path(tmp_path):
    """A candidate #11 admits with an unknown band keeps its nulls and reasons.

    The criterion asks a candidate admitted with unknown F0, key, loudness,
    bands or envelope to keep its nulls and reasons and still rank. #12's
    frequency evidence now returns its own unavailable score for an incomplete
    band set instead of summing a missing value; #12 owns that semantics and
    tests/test_dsp_baseline.py carries the focused regression rows.
    """

    built = build_library(tmp_path, {"kick": {"key": "known"}, "basses": [],
                                     "palette": {"kick": True, "bass": None}})
    with closing(open_database(built.database)) as connection:
        repository = LibraryRepository(connection)
        kick = repository.get_sample(built.kick_id, built.version).sample
        bands = {name: None for name in ("band_sub", "band_bass", "band_low_mid", "band_mid",
                                         "band_high_mid", "band_high")}
        candidate = replace(_variant(built_bass(), "bass-001", values=bands),
                            analysis_version=built.version)
    result = ranking.rank_candidates(kick, (candidate,), policy=ranking.RankingPolicy())
    # The candidate is neither dropped nor invented: its frequency dimension is
    # unavailable, its other dimensions still score it, and the measurement keeps
    # its null and its reason.
    assert len(result.ranked) == 1 and result.unscored == ()
    entry = next(entry for entry in result.ranked[0].dsp_dimensions
                 if entry.dimension == "frequency")
    assert entry.compatibility is None
    assert entry.unavailable_reason == "candidate_band_unknown"
    assert result.ranked[0].compatibility is not None
    measurement = next(item for item in candidate.features.measurements
                       if item.name == "band_sub")
    assert measurement.value is None and measurement.unavailable_reason


