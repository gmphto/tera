def _with_values(sample, values):
    """A copy of one sample with the named measurements replaced.

    A null value becomes the explicit unknown #11 admits: value None, no
    confidence and a stored reason. A known fundamental or tempo replacement is
    given the reliability the contract requires when the fixture carried none.
    """

    measurements = []
    for item in sample.features.measurements:
        if item.name not in values:
            measurements.append(item)
            continue
        value = values[item.name]
        if value is None:
            measurements.append(replace(item, value=None, confidence=None,
                                        unavailable_reason="not_measured"))
            continue
        confidence = item.confidence
        if item.name in ("fundamental", "tempo") and confidence is None:
            confidence = 0.9
        measurements.append(replace(item, value=value, confidence=confidence,
                                    unavailable_reason=None))
    return replace(sample, features=replace(sample.features, measurements=tuple(measurements)))


def _variant(sample, sample_id, *, role=None, values=None, key=None, frames=None):
    """One stored sample of a fixture case, with a synthetic local path."""

    values = dict(values or {})
    if frames == 0:
        # A zero-frame file has no time for a millisecond measurement; the
        # contract's own sample check refuses one that outlives the duration.
        values.update({"transient_position": 0.0, "attack": 0.0, "decay": 0.0})
    changed = _with_values(sample, values)
    if key is not None:
        changed = replace(changed, features=replace(changed.features, key=key))
    if frames is not None:
        changed = replace(changed, audio=replace(
            changed.audio, frame_count=frames,
            duration_ms=0.0 if frames == 0 else frames * 1000 / changed.audio.sample_rate_hz))
    return replace(changed, sample_id=sample_id, role=role or changed.role,
                   audio=replace(changed.audio,
                                 local_path="C:/tera-fixtures/" + sample_id + ".wav"))


def _generated(count, values):
    """One explicit entry per index; "index" becomes -20.0 minus the index."""

    entries = []
    for index in range(1, count + 1):
        entries.append({"id": "bass-%03d" % index,
                        "values": {name: (-20.0 - index if value == "index" else value)
                                   for name, value in (values or {}).items()}})
    return entries


def _other_descriptor():
    """A second analysis descriptor, so one row can hold a stale version."""

    descriptor = dict(batch.analysis_descriptor())
    descriptor["configuration"] = dict(descriptor["configuration"], snapshot="second-version")
    return descriptor


class Built:
    """One synthetic library: where it is, what it holds and what the palette selects."""

    def __init__(self, database, palette_id, revision, kick_id, bass_ids, version):
        self.database = database
        self.palette_id = palette_id
        self.revision = revision
        self.kick_id = kick_id
        self.bass_ids = tuple(bass_ids)
        self.version = version


def build_library(directory, spec):
    """One synthetic library on disk, ready for a recommendation request."""

    spec = spec or {}
    database = str(Path(directory) / "library.sqlite3")
    with closing(open_database(database)) as connection:
        repository = LibraryRepository(connection)
        version = repository.register_analysis_version(batch.analysis_descriptor())
        kick_fixture, bass_fixture = _fixture_samples()[:2]
        kick_spec = spec.get("kick", {})
        kick = replace(_variant(
            kick_fixture, kick_spec.get("id", "kick-001"), role="kick",
            values=kick_spec.get("values"),
            key=KNOWN_KEY if kick_spec.get("key", "known") == "known" else None,
            frames=kick_spec.get("frames")), analysis_version=version)
        _store_kick(repository, connection, kick, version, kick_spec)
        bass_ids = _store_basses(repository, connection, bass_fixture, version,
                                 spec.get("basses"))
        project = repository.create_project("recommendation-fixture", palette_name="Fixture")
        revision = _select(repository, project.palette_id, kick.sample_id, bass_ids,
                           spec.get("palette", {}), spec.get("context", "unset"))
        _apply_states(repository, connection, spec, bass_ids)
    return Built(database, project.palette_id, revision, kick.sample_id, bass_ids, version)


def _store_kick(repository, connection, kick, version, spec):
    """Store the kick row in the analysis state the case asks for."""

    state = spec.get("analysis", "current")
    if state == "current":
        repository.import_sample(kick, content_sha256=SYNTHETIC_HASHES[kick.sample_id],
                                 file_status=spec.get("status", "present"))
        return
    if state == "stale":
        other = repository.register_analysis_version(_other_descriptor())
        repository.import_sample(replace(kick, analysis_version=other),
                                 content_sha256=SYNTHETIC_HASHES[kick.sample_id])
        return
    kick = replace(kick, analysis_version=version)
    # "absent" and the queue states: an indexed row with no analysis at all,
    # exactly as #22 leaves one before #23 stores anything.
    repository.insert_path_record(
        "C:/tera-fixtures/" + kick.sample_id + ".wav", role="kick",
        content_sha256=SYNTHETIC_HASHES[kick.sample_id],
        sample_rate_hz=kick.audio.sample_rate_hz, channels=kick.audio.channels,
        frame_count=kick.audio.frame_count, duration_ms=kick.audio.duration_ms,
        file_status=spec.get("status", "present"), sample_id=kick.sample_id)
    if state in ("pending", "failed"):
        queue.enqueue(connection, version)
        if state == "failed":
            connection.execute(
                "UPDATE job_items SET state = 'failed', error_stage = 'extract', "
                "error_code = 'extractor_failure', error_message = 'synthetic failure' "
                "WHERE sample_id = ?", ("sha256:" + SYNTHETIC_HASHES[kick.sample_id],))


def _store_basses(repository, connection, bass_fixture, version, spec):
    """Store every candidate row of the case and return their ids."""

    entries = _generated(spec.get("count", 0), spec.get("values")) \
        if isinstance(spec, dict) else list(spec or [])
    ids = []
    for entry in entries:
        sample_id = entry["id"]
        key = UNKNOWN_KEY if entry.get("key") == "unknown" else None
        sample = replace(_variant(bass_fixture, sample_id, role=entry.get("role", "bass"),
                                  values=entry.get("values"), key=key),
                         analysis_version=version)
        if entry.get("analysis", "current") == "stale":
            other = repository.register_analysis_version(_other_descriptor())
            repository.import_sample(replace(sample, analysis_version=other),
                                     content_sha256=SYNTHETIC_HASHES[sample_id])
        else:
            repository.import_sample(sample, content_sha256=SYNTHETIC_HASHES[sample_id],
                                     file_status=entry.get("status", "present"))
        ids.append(sample_id)
    return ids


def _select(repository, palette_id, kick_id, bass_ids, palette, context):
    """Select the palette's items and context and return the stored revision."""

    revision = 0
    if palette.get("kick", True):
        revision = repository.set_palette_item(palette_id, "kick", kick_id,
                                               expected_revision=revision).revision
    bass = palette.get("bass")
    if bass:
        revision = repository.set_palette_item(palette_id, "bass", bass,
                                               expected_revision=revision).revision
    if context == "known":
        revision = repository.set_palette_context(palette_id, _song_context(),
                                                  expected_revision=revision).revision
    return revision


def _apply_states(repository, connection, spec, bass_ids):
    """Apply the states a case needs after the palette selection exists."""

    after = spec.get("after", {})
    for sample_id, status in (after.get("status") or {}).items():
        repository.mark_file_status(sample_id, status)
    for sample_id in after.get("role_edits") or ():
        connection.execute("UPDATE samples SET role = 'bass' WHERE sample_id = ?", (sample_id,))
    for sample_id in after.get("pruned") or ():
        # #71 pruning removes the sample row; the palette item deliberately has
        # no foreign key, so the selection survives and the kick reads as absent.
        repository.delete_sample(sample_id)


class ScriptedTransport:
    """A test-local #14 transport: deterministic answers and an ordered call log.

    Every response is built from the payload the adapter sent, so it always
    echoes the asked question id, dimension and prompt version. A per-dimension
    override lets one case answer one dimension differently, an optional gate
    blocks a send until the test releases it, and an optional hook runs on every
    send.
    """

    def __init__(self, spec, *, on_send=None):
        self.source = spec.get("source", "double")
        self.interface_name = spec.get("interface_name", "jev-contract-double")
        self.spec = spec
        self.on_send = on_send
        self.gate = None
        self.blocked = threading.Event()
        self.release = threading.Event()
        self.calls = []

    def answer_for(self, dimension):
        """The merged answer spec of one dimension: case defaults plus override."""

        answer = {name: value for name, value in self.spec.items() if name != "overrides"}
        answer.update((self.spec.get("overrides") or {}).get(dimension) or {})
        return answer

    def send(self, payload_json, *, timeout_s):
        payload = json.loads(payload_json)
        dimension = payload["dimension"]
        self.calls.append(payload)
        if self.on_send is not None:
            self.on_send(len(self.calls))
        if self.gate is not None and self.gate(len(self.calls)):
            self.blocked.set()
            self.release.wait(timeout=30)
            self.blocked.clear()
        answer = self.answer_for(dimension)
        kind = answer.get("answer", "judgment")
        if kind == "timeout":
            raise JevTransportError("timeout", "The scripted transport timed out.")
        if kind == "service_error":
            raise JevTransportError("service_error", "The scripted transport failed.")
        if kind == "text":
            return "this is not a JSON response object"
        model_version = answer.get("model_version", DEFAULT_MODEL_VERSION)
        if kind == "abstain":
            body = {"question_id": payload["question_id"], "dimension": dimension, "label": None,
                    "probabilities": None, "confidence": None, "model_version": model_version,
                    "prompt_version": payload["prompt_version"],
                    "unavailable_reason": "model_abstained"}
            return json.dumps(body, allow_nan=False, sort_keys=True)
        probabilities = answer.get("probabilities", list(DEFAULT_PROBABILITIES))
        # 0.8 is the #11/#12 reliability threshold: a scripted judgment at it is
        # not uncertain, and a case that wants an uncertain result answers lower.
        confidence = answer.get("confidence", 0.8)
        labels = ("very-poor", "poor", "neutral", "good", "excellent")
        body = {"question_id": payload["question_id"], "dimension": dimension,
                "label": labels[probabilities.index(max(probabilities))],
                "probabilities": [{"label": name, "probability": value}
                                  for name, value in zip(labels, probabilities)],
                "confidence": confidence, "model_version": model_version,
                "prompt_version": payload["prompt_version"], "unavailable_reason": None}
        return json.dumps(body, allow_nan=False, sort_keys=True)


def collaborators_for(case, *, built=None, on_send=None, gate=None):
    """The collaborators and scripted transport one case asks for."""

    spec = case.get("transport")
    transport = None
    if spec is not None and spec.get("kind") != "none":
        transport = ScriptedTransport(spec, on_send=on_send)
        if gate is not None:
            transport.gate = gate
    return RecommendationCollaborators(transport=transport, environ=case.get("environ", {}),
                                       cache=case.get("cache"), monotonic=case.get("monotonic")), \
        transport


def _request_body(built, request):
    body = dict(request)
    body["palette_id"] = built.palette_id
    revision = body.pop("revision", "current")
    if revision == "current":
        revision = built.revision
    elif revision == "stale":
        revision = built.revision - 1
    body["revision"] = revision
    return body


def check_reply(reply, expect, *, built, previous):
    """Assert one response against one hand-written expectation."""

    assert reply.status == expect["status"], reply.raw
    if expect["status"] != 200:
        assert reply.body["error"]["code"] == expect["code"], reply.raw
        assert reply.body["error"]["details"] == _details(expect.get("details", {}), built), \
            reply.raw
        return None
    assert set(reply.body) == {"api_schema", "recommendation", "run"}, reply.raw
    assert reply.body["api_schema"] == "1.0"
    recommendation, run = reply.body["recommendation"], reply.body["run"]
    if "mode" in expect:
        assert recommendation["mode"] == expect["mode"], reply.raw
    if "jev_status" in expect:
        assert run["ranking"]["jev_status"] == expect["jev_status"], reply.raw
    if "counts" in expect:
        assert run["counts"] == expect["counts"], reply.raw
    if "evidence" in expect:
        assert run["evidence"] == expect["evidence"], reply.raw
    if "exclusions" in expect:
        assert run["exclusions"] == expect["exclusions"], reply.raw
    if "limit_reason" in expect:
        assert run["retrieval"]["limit_reason"] == expect["limit_reason"], reply.raw
    if "model_versions" in expect:
        assert run["jev"]["model_versions"] == expect["model_versions"], reply.raw
    if "shortlist_size_requested" in expect:
        assert run["retrieval"]["shortlist_size_requested"] == expect["shortlist_size_requested"]
    if "result_ids" in expect:
        assert [record["candidate_id"] for record in recommendation["results"]] == \
            expect["result_ids"], reply.raw
    if "alternative_ids" in expect:
        assert recommendation["alternatives"] == expect["alternative_ids"], reply.raw
    # Every alternative is inside the returned results, every evidence count is
    # exactly one of the four sources per weighted dimension of a scored
    # candidate, and no case returns 500.
    assert set(recommendation["alternatives"]) <= {record["candidate_id"]
                                                   for record in recommendation["results"]}
    evidence = run["evidence"]
    assert evidence["interface"] + evidence["double"] + evidence["unavailable"] \
        + evidence["cache"] == 5 * run["counts"]["scored"]
    assert run["counts"]["returned"] == min(run["counts"]["requested"], run["counts"]["scored"])
    assert run["counts"]["shortlisted"] == run["retrieval"]["shortlist_size_returned"]
    if "sample_ids" in expect:
        ids = [sample["sample_id"] for sample in recommendation["samples"]]
        assert sorted(ids) == sorted(expect["sample_ids"]), reply.raw
        assert len(ids) == len(set(ids)), reply.raw
    if "similarity_null" in expect:
        nulls = {record["candidate_id"] for record in recommendation["results"]
                 if record["similarity"] is None}
        assert nulls == set(expect["similarity_null"]), reply.raw
    if "unknown_measurement" in expect:
        _check_unknown(recommendation, expect["unknown_measurement"])
    if "same_recommendation_as" in expect:
        assert recommendation == previous[expect["same_recommendation_as"]]["recommendation"]
    if "same_run_id_as" in expect:
        assert run["run_id"] == previous[expect["same_run_id_as"]]["run"]["run_id"]
    if "different_run_id_from" in expect:
        assert run["run_id"] != previous[expect["different_run_id_from"]]["run"]["run_id"]
    if expect.get("dsp_baseline"):
        _check_dsp_baseline(recommendation, built)
    return reply.body


def _details(details, built):
    """One expectation's details, with the request's own palette id substituted."""

    return {name: (built.palette_id if value == "<palette>" else value)
            for name, value in details.items()}


def _check_unknown(recommendation, spec):
    """One unknown measurement keeps its null and its reason and claims no confidence."""

    sample = next(item for item in recommendation["samples"]
                  if item["sample_id"] == spec["sample_id"])
    measurement = next(item for item in sample["features"]["measurements"]
                       if item["name"] == spec["name"])
    assert measurement["value"] is None
    assert measurement["unavailable_reason"] == spec["reason"]
    assert measurement["confidence"] is None


def _check_dsp_baseline(recommendation, built):
    """The DSP-only fallback equals #12's own result for the same inputs."""

    with closing(open_database(built.database)) as connection:
        repository = LibraryRepository(connection)
        kick = repository.get_sample(built.kick_id, built.version).sample
        rows = repository.list_retrieval_rows(built.version, sample_ids=built.bass_ids)
        candidates = tuple(row.sample for row in rows if row.sample is not None)
    baseline = ranking.rank_candidates(kick, candidates, policy=ranking.RankingPolicy())
    for projected, record in zip(recommendation["results"], baseline.ranked):
        assert projected["candidate_id"] == record.candidate_id
        assert (projected["compatibility"], projected["confidence"]) == \
            (record.compatibility, record.confidence)
        # The fallback copies #12's reasons and warnings unchanged and in order.
        assert projected["reasons"] == list(record.reasons)
        assert projected["warnings"] == list(record.warnings)
        assert projected["dsp_dimensions"] == [entry.to_dict() for entry in record.dsp_dimensions]
        assert not projected["jev_judgments"]


def _hook(case, built):
    """The per-send hook one case scripts; the palette bump is the only one."""

    if case.get("on_send") != "bump_palette_revision":
        return None

    def hook(count):
        if count != 1:
            return
        with closing(open_database(built.database)) as connection:
            # Re-selecting the same kick is a documented no-op, so the change is a
            # different bass: the revision and the content hash both move.
            LibraryRepository(connection).set_palette_item(
                built.palette_id, "bass", built.bass_ids[1], expected_revision=built.revision)

    return hook


@pytest.mark.parametrize("case", CASES, ids=[case["name"] for case in CASES])
def test_the_run_cases_hold(tmp_path, case):
    built = build_library(tmp_path, case.get("library"))
    collaborators, transport = collaborators_for(case, built=built, on_send=_hook(case, built))
    running = start_service(built.database, recommendations=collaborators)
    previous = []
    try:
        for request, expect in zip(case["requests"], case["expect"]):
            before = 0 if transport is None else len(transport.calls)
            reply = running.client.post("/recommendations", _request_body(built, request))
            if transport is not None and "sends" in expect:
                assert len(transport.calls) - before == expect["sends"], reply.raw
            answer = check_reply(reply, expect, built=built, previous=previous)
            previous.append(answer)
        if "cache_entries" in case:
            with closing(open_database(built.database)) as connection:
                assert decision_cache.cache_stats(connection).entries == case["cache_entries"]
    finally:
        running.stop()


