def test_the_similarity_and_reasons_are_the_landed_values_verbatim(tmp_path):
    """#25's similarity pair and #12's reasons reach the wire unchanged."""

    from backend.library.retrieval import retrieve_shortlist
    from backend.palette.retrieval import RetrievalPolicy

    case = _rule_case("a fully judged 12-candidate run")
    built = build_library(tmp_path, case["library"])
    collaborators, transport = collaborators_for(case, built=built)
    running = start_service(built.database, recommendations=collaborators)
    try:
        reply = running.client.post("/recommendations", _request_body(built, case["requests"][0]))
        assert reply.status == 200, reply.raw
        with closing(open_database(built.database)) as connection:
            stored = retrieve_shortlist(connection, built.kick_id, policy=RetrievalPolicy())
            rows = LibraryRepository(connection).list_retrieval_rows(
                built.version, sample_ids=built.bass_ids)
            kick = LibraryRepository(connection).get_sample(built.kick_id, built.version).sample
            candidates = tuple(row.sample for row in rows if row.sample is not None)
        ranked_by_id = {record.sample_id: record for record in stored.result.ranked}
        baseline = ranking.rank_candidates(kick, candidates, policy=ranking.RankingPolicy())
        baseline_by_id = {record.candidate_id: record for record in baseline.ranked}
        for projected in reply.body["recommendation"]["results"]:
            candidate_id = projected["candidate_id"]
            retrieved = ranked_by_id[candidate_id]
            assert projected["similarity"] == retrieved.similarity
            assert projected["similarity_unavailable_reason"] == \
                retrieved.similarity_unavailable_reason
            # #15 keeps #12's reasons unchanged and starts its warnings with
            # #12's own, then appends its own documented codes.
            original = baseline_by_id[candidate_id]
            assert projected["reasons"] == list(original.reasons)
            assert projected["warnings"][:len(original.warnings)] == list(original.warnings)
            assert any(warning.startswith(("dimension_disagreement", "low_coverage",
                                           "low_jev_confidence", "candidate_no_jev_evidence",
                                           "jev_evidence_unavailable", "unweighted_dimension"))
                       for warning in projected["warnings"])
    finally:
        running.stop()


