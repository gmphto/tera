"""End-to-end recommendation runs over a real socket (issue #28).

Every case in tests/fixtures/api/recommendation-runs.json builds one synthetic
library under tmp_path with #21's open_database chain, #24's palette operations
and the synthetic contract samples of #9's hybrid fixture, then drives one or
more POST /recommendations requests over a socket served by #27's create_server
with #28's collaborators injected: a scripted #14 transport, #26's own cache or
a stub of it, and the process environment.

Every expectation is hand-written in the fixture file, never read back from the
implementation. No real library path, sample name, content fingerprint,
credential, endpoint or audio byte appears here. The helper shapes are:

    library.kick     key known/unknown, measurement values, status, analysis state
    library.basses   an explicit list, or {count, values} generated by index
    library.palette  which kick and bass the palette selects
    library.after    states applied after the selection: status, role_edits, pruned
    transport        double/interface source, answer, per-dimension overrides
    requests[]       the body sent; "revision" defaults to the stored one
    expect[]         status, code, details, counts, evidence, ids and so on
"""

